#!/usr/bin/env bash
# Run ariodb against a throwaway Postgres in Docker, with sample data, so you
# can try it by hand. Ctrl-C stops everything. All passwords are test values.
#
#   ./scripts/demo.sh
#   psql "postgres://coding-agent:demo-agent-token@127.0.0.1:6543/app?sslmode=disable"
#   open http://127.0.0.1:8080   (password: demo-dashboard-password)
set -euo pipefail
cd "$(dirname "$0")/.."
[ -f "$HOME/.cargo/env" ] && . "$HOME/.cargo/env"
cargo build -q
BIN=./target/debug/ariodb
PG=ariodb-demo-pg
DIR=.ariodb-demo
SERVE_PID=""
rm -rf "$DIR"; mkdir -p "$DIR"; chmod 700 "$DIR"
trap 'kill $SERVE_PID 2>/dev/null || true; docker rm -f $PG >/dev/null 2>&1 || true' EXIT

docker rm -f $PG >/dev/null 2>&1 || true
docker run -d --name $PG -e POSTGRES_PASSWORD=demo-admin-pw -e POSTGRES_DB=app \
  -p 127.0.0.1:55440:5432 postgres:16 -c wal_level=logical >/dev/null
until docker exec $PG psql -U postgres -d app -tAc 'SELECT 1' >/dev/null 2>&1; do sleep 1; done
sleep 2
until docker exec $PG psql -U postgres -d app -tAc 'SELECT 1' >/dev/null 2>&1; do sleep 1; done
docker exec -i $PG psql -q -U postgres -d app <<'SQL'
CREATE TABLE customers (id int PRIMARY KEY, name text NOT NULL, email text);
CREATE TABLE orders (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id int NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  status text NOT NULL, total numeric(10,2) NOT NULL);
CREATE TABLE secrets (id serial PRIMARY KEY, note text);
INSERT INTO customers SELECT g, 'Customer ' || g, 'c' || g || '@example.test' FROM generate_series(1, 50) g;
INSERT INTO orders (customer_id, status, total) SELECT 1 + (g % 50), 'paid', (g % 97) + 0.99 FROM generate_series(1, 1000) g;
CREATE ROLE ariodb_gw LOGIN PASSWORD 'demo-gw-pw';
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO ariodb_gw;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO ariodb_gw;
SQL

cat > "$DIR/ariodb.toml" <<EOF
[database]
url = "postgres://ariodb_gw:demo-gw-pw@127.0.0.1:55440/app"

[limits]
max_rows_per_write = 200
statement_timeout_ms = 5000

[journal]
dir = "$DIR"

[dashboard]
listen = "127.0.0.1:8080"
public_url = "http://127.0.0.1:8080"
config_writes = true

[[agents]]
name = "coding-agent"
access = "read_write"
tables = ["orders", "customers"]
token_env = "DEMO_AGENT_TOKEN"

[[approvers]]
name = "ops"
type = "dashboard"

[[rules]]
name = "customer-emails-need-a-human"
condition = "sql.verb == 'select' && 'customers' in sql.tables && sql.statement.contains('email')"
verdict = "approve"
approve = ["ops"]
reason = "reading customer emails needs a human"

[[rules]]
name = "no-file-functions"
condition = "sets.intersects(sql.functions, ['pg_read_file', 'pg_ls_dir'])"
verdict = "deny"
reason = "filesystem-reaching functions are off-limits"
EOF
export DEMO_AGENT_TOKEN=demo-agent-token
ARIODB_JOURNAL_URL=postgres://postgres:demo-admin-pw@127.0.0.1:55440/app $BIN --config "$DIR/ariodb.toml" setup
printf 'demo-dashboard-password\n' | $BIN --config "$DIR/ariodb.toml" dashboard-password >/dev/null
export ARIODB_JOURNAL_URL=postgres://postgres:demo-admin-pw@127.0.0.1:55440/app
$BIN --config "$DIR/ariodb.toml" serve &
SERVE_PID=$!
until nc -z 127.0.0.1 6543 2>/dev/null; do sleep 0.2; done

# A little agent activity so the dashboard has something to show.
A="host=host.docker.internal port=6543 user=coding-agent dbname=app sslmode=disable"
run() { docker run --rm -e PGPASSWORD=$DEMO_AGENT_TOKEN postgres:16 psql "$A" -c "$1" >/dev/null 2>&1 || true; }
run "SELECT count(*) FROM orders"
run "UPDATE orders SET status = 'refunded' WHERE id IN (5, 6, 7)"
run "DELETE FROM customers WHERE id = 9"
run "DELETE FROM orders"
run "UPDATE orders SET status = 'void' WHERE id < 600"
run "SELECT pg_read_file('/etc/passwd')"
run "SELECT * FROM secrets"
( docker run --rm -e PGPASSWORD=$DEMO_AGENT_TOKEN postgres:16 psql "$A" -c "SELECT name, email FROM customers LIMIT 3" >/dev/null 2>&1 || true ) &

echo
echo "ariodb demo is running."
echo "  Dashboard: http://127.0.0.1:8080  (user root, password demo-dashboard-password)"
echo "  Agent:     psql \"postgres://coding-agent:demo-agent-token@127.0.0.1:6543/app?sslmode=disable\""
echo "Press Ctrl-C to stop."
wait $SERVE_PID
