BEGIN INSERT INTO order_log (order_id) VALUES (NEW.id); RETURN NEW; END $$;
CREATE TRIGGER orders_log AFTER UPDATE ON orders FOR EACH ROW
  WHEN (NEW.status = 'audited') EXECUTE FUNCTION log_order();
