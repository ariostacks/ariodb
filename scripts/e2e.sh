WORK=$(mktemp -d)
trap 'kill $SERVE_PID $MOCK_PID 2>/dev/null || true; docker rm -f $PG >/dev/null 2>&1 || true; rm -rf "$WORK"' EXIT
python3 -I "$(dirname "$0")/mock_services.py" $MOCK "$WORK/mock.log" &
