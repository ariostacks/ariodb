#!/usr/bin/env bash
# End-to-end test: a real Postgres in Docker, ariodb in front of it, and an
# agent doing good and bad things. Ends by undoing the agent's work and
# checking the data is exactly as it was.
#
# Needs Docker and a built ariodb (cargo build). All passwords here are
# throwaway test values.
set -euo pipefail

cd "$(dirname "$0")/.."
BIN=./target/debug/ariodb
PG=ariodb-e2e-pg
PORT=55433
PROXY=6544
WORK=$(mktemp -d)
trap 'kill $SERVE_PID 2>/dev/null || true; docker rm -f $PG >/dev/null 2>&1 || true; rm -rf "$WORK"' EXIT

# Wait for ariodb to listen; fail fast if it exits instead.
wait_for_proxy() {
  for _ in $(seq 1 100); do
    nc -z 127.0.0.1 $PROXY 2>/dev/null && return 0
    kill -0 $SERVE_PID 2>/dev/null || { cat "$WORK"/serve*.log; fail "ariodb exited"; }
    sleep 0.2
  done
  fail "ariodb did not start"
}
pass() { printf '  \033[32mpass\033[0m %s\n' "$1"; }
fail() { printf '  \033[31mFAIL\033[0m %s\n' "$1"; exit 1; }

admin() { docker exec -i $PG psql -q -v ON_ERROR_STOP=1 -U postgres -d app "$@"; }
# Run SQL through the proxy as an agent. Prints psql output, never fails.
agent() {
  docker run --rm -e PGPASSWORD="$2" postgres:16 \
    psql "host=host.docker.internal port=$PROXY user=$1 dbname=app sslmode=disable" -c "$3" 2>&1 || true
}
# Same, but the SQL is a psql script on stdin (needed for \bind).
agent_script() {
  printf '%s\n' "$3" | docker run --rm -i -e PGPASSWORD="$2" postgres:16 \
    psql "host=host.docker.internal port=$PROXY user=$1 dbname=app sslmode=disable" 2>&1 || true
}
expect() { # expect <description> <needle> <output>
  if grep -q -- "$2" <<<"$3"; then pass "$1"; else echo "$3"; fail "$1"; fi
}
fingerprint() {
  admin -tAc "SELECT md5(string_agg(t, '|' ORDER BY t)) FROM (SELECT c::text AS t FROM customers c UNION ALL SELECT o::text FROM orders o) x"
}

echo "starting Postgres"
docker rm -f $PG >/dev/null 2>&1 || true
docker run -d --name $PG -e POSTGRES_PASSWORD=local-test-only-pw -e POSTGRES_DB=app \
  -p 127.0.0.1:$PORT:5432 postgres:16 -c wal_level=logical \
  -c ssl=on -c ssl_cert_file=/etc/ssl/certs/ssl-cert-snakeoil.pem \
  -c ssl_key_file=/etc/ssl/private/ssl-cert-snakeoil.key >/dev/null
until docker exec $PG psql -U postgres -d app -tAc 'SELECT 1' >/dev/null 2>&1; do sleep 1; done
sleep 2
until docker exec $PG psql -U postgres -d app -tAc 'SELECT 1' >/dev/null 2>&1; do sleep 1; done

admin <<'SQL'
CREATE TABLE customers (id int PRIMARY KEY, name text NOT NULL, email text);
CREATE TABLE orders (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id int NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  status text NOT NULL,
  total numeric(10,2) NOT NULL,
  total_with_tax numeric(10,2) GENERATED ALWAYS AS (total * 1.2) STORED
);
CREATE TABLE secrets (id serial PRIMARY KEY, note text);
CREATE TABLE order_log (id serial PRIMARY KEY, order_id int);
CREATE FUNCTION log_order() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN INSERT INTO order_log (order_id) VALUES (NEW.id); RETURN NEW; END $$;
CREATE TRIGGER orders_log AFTER UPDATE ON orders FOR EACH ROW
  WHEN (NEW.status = 'audited') EXECUTE FUNCTION log_order();
INSERT INTO customers SELECT g, 'Customer ' || g, 'c' || g || '@example.test' FROM generate_series(1, 50) g;
INSERT INTO orders (customer_id, status, total)
  SELECT 1 + (g % 50), 'paid', (g % 97) + 0.99 FROM generate_series(1, 1000) g;
CREATE ROLE ariodb_gw LOGIN PASSWORD 'gw-local-test-only';
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO ariodb_gw;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO ariodb_gw;
CREATE ROLE ariodb_journal LOGIN REPLICATION PASSWORD 'journal-local-test-only';
SQL

cat > "$WORK/ariodb.toml" <<EOF
[database]
url = "postgres://ariodb_gw:gw-local-test-only@127.0.0.1:$PORT/app"
tls = "require"

[limits]
max_rows_per_write = 500
statement_timeout_ms = 5000

[proxy]
listen = "127.0.0.1:$PROXY"

[journal]
enabled = true
dir = "$WORK/journal"
slot = "ariodb"
publication = "ariodb"

[[agents]]
name = "coding-agent"
access = "read_write"
tables = ["orders", "customers"]
token_env = "E2E_AGENT_TOKEN"

[[agents]]
name = "support-bot"
access = "read_only"
tables = ["orders"]
token_env = "E2E_BOT_TOKEN"

[[rules]]
name = "no-file-functions"
condition = "sets.intersects(sql.functions, ['pg_read_file', 'pg_ls_dir'])"
verdict = "deny"
reason = "Filesystem-reaching functions are off-limits"

[[rules]]
name = "no-big-customer-changes"
stage = "after"
condition = "'customers' in effects.tables && effects.rows > 30"
verdict = "deny"
reason = "changes of over 30 rows that touch customers need a human"
EOF
export E2E_AGENT_TOKEN=agent-token-local-test-only E2E_BOT_TOKEN=bot-token-local-test-only
export ARIODB_JOURNAL_URL=postgres://ariodb_journal:journal-local-test-only@127.0.0.1:$PORT/app
unset ARIODB_DATABASE_URL ARIODB_ADMIN_URL
CFG=(--config "$WORK/ariodb.toml")

# Setup needs table ownership, so run it as the admin.
ARIODB_JOURNAL_URL=postgres://postgres:local-test-only-pw@127.0.0.1:$PORT/app $BIN "${CFG[@]}" setup >/dev/null
pass "setup"

$BIN "${CFG[@]}" serve >"$WORK/serve.log" 2>&1 &
SERVE_PID=$!
wait_for_proxy
BEFORE=$(fingerprint)

T=$E2E_AGENT_TOKEN
echo "database TLS"
expect "ariodb reaches the database over TLS" "| t" "$(agent coding-agent $E2E_AGENT_TOKEN "SELECT 'ssl', ssl FROM pg_stat_ssl WHERE pid = pg_backend_pid()")"

echo "refusals"
expect "wrong token is rejected"        "authentication failed"  "$(agent coding-agent wrong "SELECT 1")"
expect "read-only agent cannot write"   "is read only"           "$(agent support-bot $E2E_BOT_TOKEN "UPDATE orders SET status='x' WHERE id=1")"
expect "hidden write is seen"           "is read only"           "$(agent support-bot $E2E_BOT_TOKEN "EXPLAIN ANALYZE DELETE FROM orders WHERE id=1")"
expect "delete without WHERE refused"   "destructive"            "$(agent coding-agent $T "DELETE FROM orders")"
expect "drop refused"                   "destructive"            "$(agent coding-agent $T "DROP TABLE orders")"
expect "other tables refused"           "may not use table"      "$(agent coding-agent $T "SELECT * FROM secrets")"
expect "bulk write rolled back"         "the limit is 500"       "$(agent coding-agent $T "UPDATE orders SET status='void' WHERE id <= 800")"
expect "trigger side effect rolled back" "order_log"             "$(agent coding-agent $T "UPDATE orders SET status='audited' WHERE id = 5")"
expect "BEGIN refused"                  "own transaction"        "$(agent coding-agent $T "BEGIN")"
[ "$(fingerprint)" = "$BEFORE" ] && pass "refused statements changed nothing" || fail "data changed"

echo "rules"
expect "rule denies by function" "Filesystem-reaching" "$(agent coding-agent $T "SELECT pg_ls_dir('.')")"
expect "after-stage rule rolls back" "over 30 rows" "$(agent coding-agent $T "DELETE FROM customers WHERE id IN (4, 5)")"
expect "after-stage rollback left no trace" "2" "$(admin -tAc "SELECT count(*) FROM customers WHERE id IN (4, 5)")"
cp "$WORK/ariodb.toml" "$WORK/ariodb.toml.orig"
cat >> "$WORK/ariodb.toml" <<'TOML'

[[rules]]
name = "hot-added"
condition = "sql.verb == 'select' && 'customers' in sql.tables"
verdict = "deny"
reason = "added while running"
TOML
sleep 3
expect "hot reload picks up a new rule" "added while running" "$(agent coding-agent $T "SELECT count(*) FROM customers")"
cp "$WORK/ariodb.toml.orig" "$WORK/ariodb.toml"
sleep 3
expect "hot reload removes it again" "(1 row)" "$(agent coding-agent $T "SELECT count(*) FROM customers")"
printf 'this is not toml [[[' >> "$WORK/ariodb.toml"
sleep 3
expect "a broken config is rejected, the old one kept" "(1 row)" "$(agent coding-agent $T "SELECT count(*) FROM customers")"
expect "and the reason is logged" "kept the previous config" "$(cat "$WORK/serve.log")"
cp "$WORK/ariodb.toml.orig" "$WORK/ariodb.toml"
sleep 3

mkdir -p "$WORK/fixtures"
cat > "$WORK/fixtures/policy.json" <<'JSON'
[
  {"name": "file functions denied", "action": {"agent": "coding-agent", "sql": {"statement": "SELECT pg_read_file('/etc/hosts')"}}, "match": {"verdict": "deny", "rule": "no-file-functions"}},
  {"name": "drops denied by policy", "action": {"agent": "coding-agent", "sql": {"statement": "DROP TABLE orders"}}, "match": {"verdict": "deny", "rule": "policy"}},
  {"name": "reads allowed", "action": {"agent": "support-bot", "sql": {"statement": "SELECT * FROM orders"}}, "match": {"verdict": "allow"}}
]
JSON
$BIN "${CFG[@]}" test "$WORK/fixtures" >/dev/null && pass "ariodb test: fixtures match (exit 0)" || fail "fixtures should match"
cat > "$WORK/fixtures/drift.json" <<'JSON'
{"name": "wrong expectation", "action": {"agent": "support-bot", "sql": {"statement": "SELECT * FROM orders"}}, "match": {"verdict": "deny"}}
JSON
set +e; $BIN "${CFG[@]}" test "$WORK/fixtures" >/dev/null; code=$?; set -e
[ $code -eq 1 ] && pass "ariodb test: drift exits 1" || fail "drift should exit 1, got $code"
expect "explain shows the deciding rule" "deny  (decided by: no-file-functions)" "$($BIN "${CFG[@]}" explain --agent coding-agent "SELECT pg_read_file('x')")"

echo "agent work and undo"
OUT=$(agent coding-agent $T "UPDATE orders SET status='refunded', total=0 WHERE id IN (10,11,12); INSERT INTO customers VALUES (100,'New Co',NULL); INSERT INTO orders (customer_id,status,total) VALUES (100,'paid',9.99); DELETE FROM customers WHERE id = 3")
expect "normal writes allowed" "DELETE 1" "$OUT"
sleep 1.5
SESSION=$($BIN "${CFG[@]}" sessions | awk 'NR==2{print $1}')
[ -n "$SESSION" ] && pass "journal recorded session $SESSION" || fail "no session recorded"
expect "undo restores 26 rows incl. cascade" "26 rows restored" "$($BIN "${CFG[@]}" undo --session "$SESSION" --apply 2>&1)"
[ "$(fingerprint)" = "$BEFORE" ] && pass "data identical to before" || fail "data differs after undo"
sleep 1.5
expect "second undo refused" "already undone" "$($BIN "${CFG[@]}" undo --session "$SESSION" --apply 2>&1 || true)"

echo "conflicts"
agent coding-agent $T "UPDATE orders SET status='agent' WHERE id IN (30,31)" >/dev/null
admin -c "UPDATE orders SET status='human fix' WHERE id = 30"
sleep 1.5
SESSION=$($BIN "${CFG[@]}" sessions | awk 'NR==2{print $1}')
expect "conflict blocks undo" "changed by others" "$($BIN "${CFG[@]}" undo --session "$SESSION" --apply 2>&1 || true)"
$BIN "${CFG[@]}" undo --session "$SESSION" --apply --skip-conflicts >/dev/null
expect "human fix kept, other row restored" "30|human fix" "$(admin -tAc "SELECT id, status FROM orders WHERE id IN (30,31) ORDER BY id")"
expect "row 31 restored" "31|paid" "$(admin -tAc "SELECT id, status FROM orders WHERE id = 31")"

echo "drivers (extended protocol)"
# psql's \bind sends Parse/Bind/Execute instead of a simple query.
expect "prepared read" "(1 row)" "$(agent_script coding-agent $T 'SELECT id, status FROM orders WHERE id = $1 \bind 7 \g')"
expect "prepared write" "UPDATE 1" "$(agent_script coding-agent $T "UPDATE orders SET status = \$1 WHERE id = \$2 \\bind 'bound' 8 \\g")"
expect "prepared write landed" "8|bound" "$(admin -tAc "SELECT id, status FROM orders WHERE id = 8")"
expect "prepared destructive refused" "destructive" "$(agent_script coding-agent $T 'DELETE FROM orders \bind \g')"
expect "prepared bulk write rolled back" "the limit is 500" "$(agent_script coding-agent $T "UPDATE orders SET status = \$1 WHERE id <= 900 \\bind 'x' \\g")"
expect "prepared bulk write left no trace" "0" "$(admin -tAc "SELECT count(*) FROM orders WHERE status = 'x'")"
expect "statement timeout enforced" "statement timeout" "$(agent coding-agent $T "SELECT pg_sleep(8)")"

cat > "$WORK/bench.sql" <<'SQL'
\set id random(1, 1000)
SELECT status, total FROM orders WHERE id = :id;
UPDATE orders SET total = total WHERE id = :id;
SQL
for mode in extended prepared; do
  OUT=$(docker run --rm -v "$WORK:/w" -e PGPASSWORD=$T postgres:16 pgbench -h host.docker.internal -p $PROXY \
        -U coding-agent -n -M $mode -c 4 -t 50 -f /w/bench.sql app 2>&1 || true)
  expect "pgbench $mode: 200 transactions" "processed: 200/200" "$OUT"
done

echo "audit"
expect "audit chain intact" "audit log intact" "$($BIN "${CFG[@]}" audit)"

echo "TLS"
kill $SERVE_PID 2>/dev/null; wait $SERVE_PID 2>/dev/null || true
openssl req -x509 -newkey rsa:2048 -nodes -days 1 -subj "/CN=localhost" \
  -addext "subjectAltName=DNS:localhost,DNS:host.docker.internal" \
  -keyout "$WORK/key.pem" -out "$WORK/cert.pem" >/dev/null 2>&1
sed -i.bak "s|^\[proxy\]$|[proxy]\ntls_cert = \"$WORK/cert.pem\"\ntls_key = \"$WORK/key.pem\"\nrequire_tls = true|" "$WORK/ariodb.toml"
$BIN "${CFG[@]}" serve >"$WORK/serve-tls.log" 2>&1 &
SERVE_PID=$!
wait_for_proxy
tls_agent() {
  docker run --rm -e PGPASSWORD="$T" postgres:16 \
    psql "host=host.docker.internal port=$PROXY user=coding-agent dbname=app sslmode=$1" -c "$2" 2>&1 || true
}
expect "TLS connection works" "SSL connection" "$(docker run --rm -e PGPASSWORD="$T" postgres:16 \
  psql "host=host.docker.internal port=$PROXY user=coding-agent dbname=app sslmode=require" -c '\conninfo' 2>&1 || true)"
expect "queries work over TLS" "(1 row)" "$(tls_agent require "SELECT 1")"
expect "plaintext refused when TLS required" "requires TLS" "$(tls_agent disable "SELECT 1")"

echo "all end-to-end checks passed"
