#!/usr/bin/env bash
# Seeded random workload for undo: a real Postgres in Docker, ariodb serve
# in front of it, and tests/sim_undo.rs driving random agent sessions and
# human writes, then checking every undo against its own prediction.
#
#   ./scripts/sim-undo.sh                    # seeds 1 to 5
#   SIM_SEEDS="42 1234" ./scripts/sim-undo.sh
#   SIM_OPS=120 SIM_SESSIONS=6 ./scripts/sim-undo.sh
#
# Each seed prints a line; a failing seed prints what ariodb did, what was
# predicted, and how to run that seed alone. Passwords are throwaway test
# values. E2E_OFFSET and E2E_NAME keep parallel runs apart, as in e2e.sh.
set -euo pipefail

cd "$(dirname "$0")/.."
[ -f "$HOME/.cargo/env" ] && . "$HOME/.cargo/env"
OFF=${E2E_OFFSET:-0}
PG=ariodb-sim-pg${E2E_NAME:+-$E2E_NAME}
PORT=$((57433 + OFF))
PROXY=$((6594 + OFF))
WORK=$(mktemp -d)
trap 'kill $SERVE_PID 2>/dev/null || true; docker rm -f $PG >/dev/null 2>&1 || true; rm -rf "$WORK"' EXIT
SERVE_PID=
# Whether something listens on a local port (bash's /dev/tcp, so no nc).
port_open() { (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; }

cargo build -q
BIN=$PWD/target/debug/ariodb

echo "starting Postgres"
docker rm -f $PG >/dev/null 2>&1 || true
docker run -d --name $PG -e POSTGRES_PASSWORD=sim-local-test-only -e POSTGRES_DB=app \
  -p 127.0.0.1:$PORT:5432 postgres:16 -c wal_level=logical >/dev/null
until docker exec $PG psql -U postgres -d app -tAc 'SELECT 1' >/dev/null 2>&1; do sleep 1; done
sleep 2
until docker exec $PG psql -U postgres -d app -tAc 'SELECT 1' >/dev/null 2>&1; do sleep 1; done

docker exec -i $PG psql -q -v ON_ERROR_STOP=1 -U postgres -d app <<'SQL'
CREATE TABLE customers (id int PRIMARY KEY, name text NOT NULL);
CREATE TABLE orders (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id int NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  status text NOT NULL,
  total numeric(10,2) NOT NULL
);
CREATE TABLE order_items (
  order_id int NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  line int NOT NULL,
  qty int NOT NULL,
  PRIMARY KEY (order_id, line)
);
CREATE ROLE ariodb_gw LOGIN PASSWORD 'gw-sim-test-only';
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO ariodb_gw;
CREATE ROLE ariodb_journal LOGIN REPLICATION PASSWORD 'journal-sim-test-only';
SQL

cat > "$WORK/ariodb.toml" <<EOF
[database]
url = "postgres://ariodb_gw:gw-sim-test-only@127.0.0.1:$PORT/app"

[limits]
max_rows_per_write = 10000
statement_timeout_ms = 5000

[proxy]
listen = "127.0.0.1:$PROXY"

[journal]
enabled = true
dir = "$WORK/journal"

[dashboard]
listen = ""

[[agents]]
name = "sim-agent"
access = "read_write"
tables = ["customers", "orders", "order_items"]
token_env = "SIM_TOKEN"
EOF
export SIM_TOKEN=sim-agent-token-test-only
export ARIODB_JOURNAL_URL=postgres://ariodb_journal:journal-sim-test-only@127.0.0.1:$PORT/app
unset ARIODB_DATABASE_URL ARIODB_ADMIN_URL
ARIODB_JOURNAL_URL=postgres://postgres:sim-local-test-only@127.0.0.1:$PORT/app \
  $BIN --config "$WORK/ariodb.toml" setup >/dev/null

$BIN --config "$WORK/ariodb.toml" serve >"$WORK/serve.log" 2>&1 &
SERVE_PID=$!
for _ in $(seq 1 100); do
  port_open $PROXY && break
  kill -0 $SERVE_PID 2>/dev/null || { cat "$WORK/serve.log"; exit 1; }
  sleep 0.2
done

export SIM_PROXY_PORT=$PROXY SIM_BIN=$BIN SIM_CONFIG=$WORK/ariodb.toml
export SIM_JOURNAL=$WORK/journal/journal.jsonl
export SIM_ADMIN_URL="host=127.0.0.1 port=$PORT user=postgres password=sim-local-test-only dbname=app"
export SIM_SEEDS=${SIM_SEEDS:-"1 2 3 4 5"}
echo "running seeds: $SIM_SEEDS"
cargo test -q --test sim_undo -- --nocapture
